const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (channel) => (fn) => ipcRenderer.on(channel, (_e, data) => fn(data));

contextBridge.exposeInMainWorld('island', {
  init: () => ipcRenderer.invoke('init'),
  rect: (w, h) => ipcRenderer.send('rect', { w, h }),
  mediaCmd: (cmd) => ipcRenderer.send('media:cmd', cmd),
  setVolume: (level) => ipcRenderer.send('vol:set', level),
  toggleMute: () => ipcRenderer.send('vol:mute'),
  calConnect: (link) => ipcRenderer.invoke('cal:connect', link),
  calDisconnect: () => ipcRenderer.send('cal:disconnect'),
  calRefresh: () => ipcRenderer.send('cal:refresh'),
  findCity: (name) => ipcRenderer.invoke('weather:find', name),
  pickCity: (city) => ipcRenderer.invoke('weather:pick', city),
  weatherRefresh: () => ipcRenderer.send('weather:refresh'),
  clipCopy: (id) => ipcRenderer.send('clip:copy', id),
  clipClear: () => ipcRenderer.send('clip:clear'),
  clipPin: (id) => ipcRenderer.send('clip:pin', id),
  clipRemove: (id) => ipcRenderer.send('clip:remove', id),
  setDisplay: (id) => ipcRenderer.send('display:set', id),
  focusWindow: () => ipcRenderer.send('win:focus'),
  blurWindow: () => ipcRenderer.send('win:blur'),
  onDisplays: on('displays'),
  onHidden: on('hidden'),
  shelfAdd: (files) => ipcRenderer.send('shelf:add', [...files].map((f) => webUtils.getPathForFile(f)).filter(Boolean)),
  shelfRemove: (id) => ipcRenderer.send('shelf:remove', id),
  shelfClear: () => ipcRenderer.send('shelf:clear'),
  shelfOpen: (id) => ipcRenderer.send('shelf:open', id),
  shelfReveal: (id) => ipcRenderer.send('shelf:reveal', id),
  shelfDrag: (id) => ipcRenderer.send('shelf:drag', id),
  setTasks: (tasks) => ipcRenderer.send('tasks:set', tasks),
  clearMsgs: () => ipcRenderer.send('msgs:clear'),
  setNotifyFrom: (from) => ipcRenderer.send('notify:from', from),
  setAgent: (name) => ipcRenderer.send('agent:set', name),
  copy: (text) => ipcRenderer.send('copy', text),
  setAutostart: (enabled) => ipcRenderer.send('autostart', enabled),
  notify: (title, body) => ipcRenderer.send('notify', { title, body }),
  open: (url) => ipcRenderer.send('open', url),
  quit: () => ipcRenderer.send('quit'),
  onMedia: on('media'), onArt: on('art'), onVol: on('vol'), onCal: on('cal'), onWeather: on('weather'),
  onMsgs: on('msgs'), onMsg: on('msg'), onNotifyAccess: on('notifyAccess'),
  onClips: on('clips'), onShelf: on('shelf'), onSys: on('sys'), onAgent: on('agent'),
  onToggle: on('toggle'), onDebug: on('debug'),
});
